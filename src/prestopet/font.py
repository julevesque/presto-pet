# Accent marks, three columns wide, placed above the letter
_MARKS = {
    "acute": ("001", "010"),
    "grave": ("100", "010"),
    "circ": ("010", "101"),
    "trema": ("101", "000"),
}

_ACCENTED = {
    "é": ("e", "acute"), "è": ("e", "grave"), "ê": ("e", "circ"), "ë": ("e", "trema"),
    "à": ("a", "grave"), "â": ("a", "circ"), "î": ("i", "circ"), "ï": ("i", "trema"),
    "ô": ("o", "circ"), "û": ("u", "circ"), "ù": ("u", "grave"), "ü": ("u", "trema"),
    "É": ("E", "acute"), "È": ("E", "grave"), "Ê": ("E", "circ"), "À": ("A", "grave"),
}

_ALIASES = {"’": "'", "«": '"', "»": '"', "…": "."}

_cache = {}


def glyph(c):
    """(width, [(x, y, w)]) runs of ink, y from the top of the capitals (may be negative for
    the accents of capitals)."""
    g = _cache.get(c)
    if g is not None:
        return g
    c2 = _ALIASES.get(c, c)
    mark = None
    if c2 in _ACCENTED:
        c2, mark = _ACCENTED[c2]
    spec = _GLYPHS.get(c2) or _GLYPHS["?"]
    rows = spec.split(" ")
    width = len(rows[0])
    runs = _runs(rows, 0, 0)
    if mark:
        top = -2 if c2.isupper() else 0
        if width < 3:
            runs = [r for r in runs if r[1] >= 2]   # narrow letter (i): the accent replaces its dot
        runs = runs + _runs(_MARKS[mark], (width - 3) // 2, top)
    g = (width, runs)
    _cache[c] = g
    return g


def _runs(rows, dx, dy):
    out = []
    for y, row in enumerate(rows):
        x = 0
        n = len(row)
        while x < n:
            if row[x] == "1":
                end = x
                while end < n and row[end] == "1":
                    end += 1
                out.append((x + dx, y + dy, end - x))
                x = end
            else:
                x += 1
    return out


def width(text, scale=1):
    """Width of the text in pixels."""
    if not text:
        return 0
    w = 0
    for c in text:
        w += glyph(c)[0] + SPACING
    return (w - SPACING) * scale


def wrap(text, max_width, scale):
    """Splits the text into lines no wider than max_width pixels."""
    lines = []
    for paragraph in text.split("\n"):
        line = ""
        for word in paragraph.split(" "):
            candidate = word if not line else line + " " + word
            if line and width(candidate, scale) > max_width:
                lines.append(line)
                line = word
            else:
                line = candidate
        lines.append(line)
    return lines
